/**
 * Generates the n8n property descriptions from the vendored Papierkram OpenAPI
 * document.
 *
 * The Papierkram API is in BETA and its field names move. Hand-written property
 * lists rot silently: a renamed field keeps compiling and only fails at runtime
 * against a customer's account. Generating them turns that into "regenerate and
 * read the diff".
 *
 * Structure — which resource exists, which operations it offers, how its URL is
 * built — is declared below and stays readable. Field names, types, enums and
 * descriptions come from the spec and are never typed by hand.
 *
 *   npm run generate
 */
