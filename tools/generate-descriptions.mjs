const LIST_META = ['page', 'page_size', 'order_by', 'order_direction'];

/* ------------------------------------------------------------------ naming */

const camel = (s) => s.replace(/[_-](\w)/g, (_, c) => c.toUpperCase());

const ACRONYMS = {
	id: 'ID',
	url: 'URL',
	pdf: 'PDF',
	vat: 'VAT',
	iban: 'IBAN',
	bic: 'BIC',
	blz: 'BLZ',
	ust: 'USt',
	idnr: 'IdNr',
	zip: 'ZIP',
	no: 'No',
};
const titleWord = (w) => ACRONYMS[w.toLowerCase()] ?? w.charAt(0).toUpperCase() + w.slice(1);
const title = (s) =>
	s
		.split(/[_\s.-]+/)
		.filter(Boolean)
		.map(titleWord)
		.join(' ');

const lit = (s) =>
	`'${String(s)
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'")
		.replace(/\n/g, ' ')}'`;

/** n8n renders the description as a hint; a trailing period reads badly there. */
const clean = (s) =>
	(s ?? '')
		.replace(/\s+/g, ' ')
		.trim()
		.replace(/\.$/, '');

/**
 * Field descriptions the way the n8n lint rules want them: "ID" rather than
 * "id", and a closing period.
 */
const describe = (s) => {
	const text = clean(s).replace(/\bid\b/g, 'ID').replace(/\bids\b/g, 'IDs');
	// One sentence stands without a period, several need one — the n8n lint has
	// a rule for each direction.
	return /[.!?]\s/.test(text) ? `${text}.` : text;
};

/* -------------------------------------------------- operation discovery */

function operationsOf(resource) {
	const base = resource.path;
	const idKey = `${base}/{id}`;
	const ops = [];
	const has = (p, m) => spec.paths[p]?.[m];

	if (has(base, 'get')) ops.push({ op: resource.singleton ? 'get' : 'getAll', method: 'get', path: base });
	if (has(base, 'post')) ops.push({ op: 'create', method: 'post', path: base });
	if (has(idKey, 'get')) ops.push({ op: 'get', method: 'get', path: idKey });
	if (has(idKey, 'put')) ops.push({ op: 'update', method: 'put', path: idKey });
	if (has(idKey, 'delete')) ops.push({ op: 'delete', method: 'delete', path: idKey });

	for (const [path, item] of Object.entries(spec.paths)) {
		if (!path.startsWith(`${base}/{id}/`)) continue;
		const action = path.slice(`${base}/{id}/`.length);
		if (action.includes('/') || action.includes('{')) continue;
		for (const method of ['get', 'post', 'put', 'delete']) {
			if (item[method]) ops.push({ op: camel(action), method, path });
		}
	}
	return ops;
}

/** "a voucher" but "an invoice" — n8n shows these strings in the action list. */
const one = (resource) => {
	const noun = resource.displayName.toLowerCase();
	return `${/^[aeiou]/.test(noun) ? 'an' : 'a'} ${noun}`;
};
const many = (resource) => (resource.plural ?? `${resource.displayName}s`).toLowerCase();

const OPERATION_LABEL = {
	getAll: ['Get Many', (r) => `Get many ${many(r)}`, (r) => `Get many ${many(r)}`],
	get: ['Get', (r) => `Get one ${resourceNoun(r)}`, (r) => `Get ${one(r)}`],
	create: ['Create', (r) => `Create ${one(r)}`, (r) => `Create ${one(r)}`],
	update: ['Update', (r) => `Update ${one(r)}`, (r) => `Update ${one(r)}`],
	delete: ['Delete', (r) => `Delete ${one(r)}`, (r) => `Delete ${one(r)}`],
};

const resourceNoun = (resource) => resource.displayName.toLowerCase();

function label(resource, entry) {
	const known = OPERATION_LABEL[entry.op];
	if (known) return { name: known[0], description: known[1](resource), action: known[2](resource) };
	const summary = clean(spec.paths[entry.path][entry.method].summary);
	const fallback = `${title(entry.op)} ${one(resource)}`;
	return {
		name: title(entry.op),
		description: summary || fallback,
		action: (summary || fallback).replace(/s*([^)]*)/g, ''),
	};
}

/* ------------------------------------------------------------- url + ids */

const parentParam = (placeholder) => camel(placeholder);
const ownIdParam = (resource) => `${resource.name}Id`;
const needsOwnId = (entry) => entry.path.includes('/{id}');

function urlExpression(resource, entry) {
	let url = entry.path;
	for (const placeholder of resource.parents ?? []) {
		url = url.replace(`{${placeholder}}`, `{{$parameter["${parentParam(placeholder)}"]}}`);
	}
	url = url.replace('{id}', `{{$parameter["${ownIdParam(resource)}"]}}`);
	return url.includes('{{') ? `=${url}` : url;
}

/* --------------------------------------------------------------- fields */

function bodySchema(entry) {
	return spec.paths[entry.path][entry.method]?.requestBody?.content?.['application/json']?.schema;
}

/** Flattens `customer: { id }` into the single leaf `customer.id`. */
function leaves(schema, prefix = '', required = new Set()) {
	const out = [];
	for (const [key, value] of Object.entries(schema.properties ?? {})) {
		const dotted = prefix ? `${prefix}.${key}` : key;
		const isRequired = required.has(key);
		if (value.type === 'object' && Object.keys(value.properties ?? {}).length > 0) {
			out.push(...leaves(value, dotted, new Set(isRequired ? value.required ?? [] : [])));
			continue;
		}
		out.push({ dotted, schema: value, required: isRequired });
	}
	return out;
}

function propertyFor(leaf) {
	const { dotted, schema } = leaf;
	const name = camel(dotted.replace(/\./g, '_'));
	const displayName = title(dotted);
	const description = describe(schema.description);
	const enumValues = [...new Set((schema.enum ?? []).filter((v) => v !== null && v !== ''))];

	if (enumValues.length > 0) {
		return {
			name,
			displayName,
			type: 'options',
			default: enumValues[0],
			description,
			options: enumValues.sort().map((v) => ({ name: title(String(v)), value: v })),
			send: dotted,
		};
	}
	if (schema.type === 'boolean') {
		const tail = (description || displayName).replace(/^whether /i, '');
		return {
			name,
			displayName,
			type: 'boolean',
			default: false,
			description: `Whether ${tail.charAt(0).toLowerCase()}${tail.slice(1)}`,
			send: dotted,
		};
	}
	if (schema.type === 'integer' || schema.type === 'number') {
		return { name, displayName, type: 'number', default: 0, description, send: dotted };
	}
	if (schema.type === 'array' || schema.type === 'object') {
		const shape = schema.type === 'array' ? 'JSON array' : 'JSON object';
		return {
			name,
			displayName,
			type: 'json',
			default: schema.type === 'array' ? '[]' : '{}',
			description: description || `${shape} in the shape the API documents for "${dotted}"`,
			send: dotted,
			parse: true,
		};
	}
	if (/color$/i.test(name)) {
		return { name, displayName, type: 'color', default: '', description, send: dotted };
	}
	if (/email/i.test(name)) {
		return {
			name,
			displayName,
			type: 'string',
			default: '',
			placeholder: 'name@email.com',
			description,
			send: dotted,
		};
	}
	return { name, displayName, type: 'string', default: '', description, send: dotted };
}

const byDisplayName = (a, b) => a.displayName.localeCompare(b.displayName);

function renderProperty(p, indent, extra = '') {
	const lines = [`${indent}{`];
	lines.push(`${indent}\tdisplayName: ${lit(p.displayName)},`);
	lines.push(`${indent}\tname: ${lit(p.name)},`);
	lines.push(`${indent}\ttype: ${lit(p.type)},`);
	if (p.options) {
		lines.push(`${indent}\toptions: [`);
		for (const o of p.options) {
			lines.push(`${indent}\t\t{ name: ${lit(o.name)}, value: ${lit(o.value)} },`);
		}
		lines.push(`${indent}\t],`);
	}
	lines.push(`${indent}\tdefault: ${typeof p.default === 'string' ? lit(p.default) : p.default},`);
	if (p.placeholder) lines.push(`${indent}\tplaceholder: ${lit(p.placeholder)},`);
	if (p.description) lines.push(`${indent}\tdescription: ${lit(describe(p.description))},`);
	if (extra) {
		lines.push(
			extra
				.split('\n')
				.map((l) => `${indent}\t${l}`)
				.join('\n'),
		);
	}
	lines.push(`${indent}},`);
	return lines.join('\n');
}

const sendBody = (p) =>
	`routing: { send: { property: ${lit(p.send)}, type: 'body'${
		p.parse ? ", value: '={{ JSON.parse($value) }}'" : ''
	} } },`;

const showFor = (resourceName, operations) =>
	[
		'displayOptions: {',
		'\tshow: {',
		`\t\tresource: [${lit(resourceName)}],`,
		`\t\toperation: [${operations.map(lit).join(', ')}],`,
		'\t},',
		'},',
	].join('\n');

const indentBlock = (block, indent) => block.split('\n').join(`\n${indent}`);

/* ------------------------------------------------------------ generation */

function generate(resource) {
	const entries = operationsOf(resource);
	if (entries.length === 0) return null;

	const out = [];
	const opOptions = entries
		.map((entry) => ({ entry, ...label(resource, entry) }))
		.sort((a, b) => a.name.localeCompare(b.name));

	out.push("import type { INodeProperties } from 'n8n-workflow';");
	if (resource.binaryUpload) {
		out.push('');
		out.push("import { uploadBinaryFile } from '../GenericFunctions';");
	}
	out.push('');
	out.push(`export const ${resource.name}Operations: INodeProperties[] = [`);
	out.push('\t{');
	out.push("\t\tdisplayName: 'Operation',");
	out.push("\t\tname: 'operation',");
	out.push("\t\ttype: 'options',");
	out.push('\t\tnoDataExpression: true,');
	out.push(`\t\tdisplayOptions: { show: { resource: [${lit(resource.name)}] } },`);
	out.push('\t\toptions: [');
	for (const option of opOptions) {
		const requestParts = [
			`method: ${lit(option.entry.method.toUpperCase())}`,
			`url: ${lit(urlExpression(resource, option.entry))}`,
		];
		if (option.entry.op === 'pdf') {
			// The postReceive binaryData action expects the body as a Buffer, which
			// it only is when the response is neither parsed as JSON nor decoded as
			// text — a decoded PDF is corrupt by the time it reaches the workflow.
			requestParts.push("encoding: 'arraybuffer'", 'json: false');
		}
		const routing = [`request: { ${requestParts.join(', ')} }`];
		if (resource.binaryUpload && option.entry.op === 'create') {
			routing.push('send: { preSend: [uploadBinaryFile] }');
		}
		if (option.entry.op === 'getAll') {
			routing.push(
				[
					'operations: {',
					'\tpagination: {',
					"\t\ttype: 'generic',",
					'\t\tproperties: {',
					"\t\t\tcontinue: '={{ $response.body.has_more === true }}',",
					"\t\t\trequest: { qs: { page: '={{ $pageCount + 1 }}' } },",
					'\t\t},',
					'\t},',
					'}',
				].join('\n\t\t\t\t\t'),
			);
			routing.push(
				"output: { postReceive: [{ type: 'rootProperty', properties: { property: 'entries' } }] }",
			);
		}
		if (option.entry.op === 'pdf') {
			routing.push(
				[
					'output: {',
					"\tpostReceive: [{ type: 'binaryData', properties: { destinationProperty: 'data' } }],",
					'}',
				].join('\n\t\t\t\t\t'),
			);
		}
		out.push('\t\t\t{');
		out.push(`\t\t\t\tname: ${lit(option.name)},`);
		out.push(`\t\t\t\tvalue: ${lit(option.entry.op)},`);
		out.push(`\t\t\t\tdescription: ${lit(option.description)},`);
		out.push(`\t\t\t\taction: ${lit(option.action)},`);
		out.push(`\t\t\t\trouting: {\n\t\t\t\t\t${routing.join(',\n\t\t\t\t\t')},\n\t\t\t\t},`);
		out.push('\t\t\t},');
	}
	out.push('\t\t],');
	out.push(`\t\tdefault: ${lit(opOptions[0].entry.op)},`);
	out.push('\t},');
	out.push('];');
	out.push('');
	out.push(`export const ${resource.name}Fields: INodeProperties[] = [`);

	const allOps = entries.map((entry) => entry.op);

	for (const placeholder of resource.parents ?? []) {
		const owner = title(placeholder).replace(/ ID$/, '').toLowerCase();
		out.push(
			renderProperty(
				{
					displayName: title(placeholder),
					name: parentParam(placeholder),
					type: 'string',
					default: '',
					description: `ID of the ${owner} the ${resource.displayName.toLowerCase()} belongs to`,
				},
				'\t',
				`required: true,\n${showFor(resource.name, allOps)}`,
			),
		);
	}

	const idOps = entries.filter(needsOwnId).map((entry) => entry.op);
	if (idOps.length > 0) {
		out.push(
			renderProperty(
				{
					displayName: `${resource.displayName} ID`,
					name: ownIdParam(resource),
					type: 'string',
					default: '',
					description: `ID of the ${resource.displayName.toLowerCase()} to work on`,
				},
				'\t',
				`required: true,\n${showFor(resource.name, idOps)}`,
			),
		);
	}

	if (resource.binaryUpload) {
		out.push(
			renderProperty(
				{
					displayName: 'Input Binary Field',
					name: 'binaryPropertyName',
					type: 'string',
					default: 'data',
					description: 'Name of the binary field of the incoming item that holds the file to upload',
				},
				'\t',
				`required: true,\n${showFor(resource.name, ['create'])}`,
			),
		);
	}

	const listEntry = entries.find((entry) => entry.op === 'getAll');
	if (listEntry) {
		const params = spec.paths[listEntry.path].get.parameters ?? [];

		out.push(
			renderProperty(
				{
					displayName: 'Return All',
					name: 'returnAll',
					type: 'boolean',
					default: false,
					description: 'Whether to return all results or only up to a given limit',
				},
				'\t',
				`routing: { send: { paginate: '={{ $value }}' } },\n${showFor(resource.name, ['getAll'])}`,
			),
		);
		out.push(
			renderProperty(
				{
					displayName: 'Limit',
					name: 'limit',
					type: 'number',
					default: 50,
					description: 'Max number of results to return',
				},
				'\t',
				[
					'typeOptions: { minValue: 1, maxValue: 100 },',
					"routing: { send: { property: 'page_size', type: 'query', value: '={{ $value }}' }, output: { maxResults: '={{ $value }}' } },",
					'displayOptions: {',
					'\tshow: {',
					`\t\tresource: [${lit(resource.name)}],`,
					"\t\toperation: ['getAll'],",
					'\t\treturnAll: [false],',
					'\t},',
					'},',
				].join('\n'),
			),
		);

		const filterParams = params.filter((p) => !LIST_META.includes(p.name));
		if (filterParams.length > 0) {
			out.push('\t{');
			out.push("\t\tdisplayName: 'Filters',");
			out.push("\t\tname: 'filters',");
			out.push("\t\ttype: 'collection',");
			out.push("\t\tplaceholder: 'Add Filter',");
			out.push('\t\tdefault: {},');
			out.push(`\t\t${indentBlock(showFor(resource.name, ['getAll']), '\t\t')}`);
			out.push('\t\toptions: [');
			const rendered = filterParams
				.map((param) => ({
					property: {
						...propertyFor({ dotted: param.name, schema: param.schema ?? { type: 'string' }, required: false }),
						description: describe(param.description),
					},
					original: param.name,
				}))
				.sort((a, b) => byDisplayName(a.property, b.property));
			for (const { property, original } of rendered) {
				out.push(
					renderProperty(property, '\t\t\t', `routing: { send: { property: ${lit(original)}, type: 'query' } },`),
				);
			}
			out.push('\t\t],');
			out.push('\t},');
		}

		out.push('\t{');
		out.push("\t\tdisplayName: 'Options',");
		out.push("\t\tname: 'options',");
		out.push("\t\ttype: 'collection',");
		out.push("\t\tplaceholder: 'Add Option',");
		out.push('\t\tdefault: {},');
		out.push(`\t\t${indentBlock(showFor(resource.name, ['getAll']), '\t\t')}`);
		out.push('\t\toptions: [');
		out.push(
			renderProperty(
				{
					displayName: 'Order By',
					name: 'orderBy',
					type: 'string',
					default: '',
					description:
						'Field to sort by. Only the fields the endpoint documents are accepted, and it only takes effect together with Order Direction',
				},
				'\t\t\t',
				"routing: { send: { property: 'order_by', type: 'query' } },",
			),
		);
		out.push(
			renderProperty(
				{
					displayName: 'Order Direction',
					name: 'orderDirection',
					type: 'options',
					default: 'asc',
					description: 'Sort direction, only effective together with Order By',
					options: [
						{ name: 'Ascending', value: 'asc' },
						{ name: 'Descending', value: 'desc' },
					],
				},
				'\t\t\t',
				"routing: { send: { property: 'order_direction', type: 'query' } },",
			),
		);
		out.push('\t\t],');
		out.push('\t},');
	}

	for (const entry of entries) {
		const schema = bodySchema(entry);
		if (!schema) continue;
		const all = leaves(schema, '', new Set(schema.required ?? [])).map((leaf) => ({
			...propertyFor(leaf),
			required: leaf.required,
		}));

		const requiredProps = all.filter((p) => p.required).sort(byDisplayName);
		const optionalProps = all.filter((p) => !p.required).sort(byDisplayName);

		for (const property of requiredProps) {
			out.push(
				renderProperty(
					property,
					'\t',
					`required: true,\n${sendBody(property)}\n${showFor(resource.name, [entry.op])}`,
				),
			);
		}
		if (optionalProps.length > 0) {
			const isCreate = entry.op === 'create';
			out.push('\t{');
			out.push(`\t\tdisplayName: ${lit(isCreate ? 'Additional Fields' : `${title(entry.op)} Fields`)},`);
			out.push(`\t\tname: ${lit(isCreate ? 'additionalFields' : `${entry.op}Fields`)},`);
			out.push("\t\ttype: 'collection',");
			out.push("\t\tplaceholder: 'Add Field',");
			out.push('\t\tdefault: {},');
			out.push(`\t\t${indentBlock(showFor(resource.name, [entry.op]), '\t\t')}`);
			out.push('\t\toptions: [');
			for (const property of optionalProps) {
				out.push(renderProperty(property, '\t\t\t', sendBody(property)));
			}
			out.push('\t\t],');
			out.push('\t},');
		}
	}

	out.push('];');
	out.push('');
	return out.join('\n');
}

/* ------------------------------------------------------------------ main */

mkdirSync(outDir, { recursive: true });

const generated = [];
for (const resource of RESOURCES) {
	const code = generate(resource);
	if (code === null) {
		console.warn(`no operations found for ${resource.name} (${resource.path})`);
		continue;
	}
	const file = `${resource.displayName.replace(/\s+/g, '')}Description.ts`;
	writeFileSync(join(outDir, file), `${HEADER}${code}`, 'utf8');
	generated.push({ resource, file: file.replace(/\.ts$/, '') });
}

const index = [HEADER, "import type { INodeProperties } from 'n8n-workflow';", ''];
for (const { resource, file } of generated) {
	index.push(`import { ${resource.name}Fields, ${resource.name}Operations } from './${file}';`);
}
index.push('');
index.push('export const resourceOptions: INodeProperties = {');
index.push("\tdisplayName: 'Resource',");
index.push("\tname: 'resource',");
index.push("\ttype: 'options',");
index.push('\tnoDataExpression: true,');
index.push('\toptions: [');
for (const { resource } of [...generated].sort((a, b) =>
	a.resource.displayName.localeCompare(b.resource.displayName),
)) {
	index.push(
		`\t\t{ name: ${lit(resource.displayName)}, value: ${lit(resource.name)}, description: ${lit(
			clean(resource.description),
		)} },`,
	);
}
index.push('\t],');
index.push("\tdefault: 'invoice',");
index.push('};');
index.push('');
index.push('export const resourceProperties: INodeProperties[] = [');
for (const { resource } of generated) {
	index.push(`\t...${resource.name}Operations,`);
	index.push(`\t...${resource.name}Fields,`);
}
index.push('];');
index.push('');

writeFileSync(join(outDir, 'index.ts'), index.join('\n'), 'utf8');
console.log(`generated ${generated.length} descriptions into ${outDir}`);
